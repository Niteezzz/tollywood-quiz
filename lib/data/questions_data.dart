List<Question> getQuestionsByCategory(QuizCategory category) {
  if (category == QuizCategory.all) return List.from(allQuestions);
  return allQuestions.where((q) => q.category == category).toList();
}

List<Question> getQuestionsByCategoryAndDifficulty(
    QuizCategory category, Difficulty difficulty) {
  return allQuestions
      .where((q) =>
          (category == QuizCategory.all || q.category == category) &&
          q.difficulty == difficulty)
      .toList();
}

List<Question> getRandomQuestions(QuizCategory category, Difficulty difficulty,
    {int count = 10}) {
  final filtered = getQuestionsByCategoryAndDifficulty(category, difficulty);
  if (filtered.isEmpty) {
    // Fall back to all categories of the same difficulty
    final byDiff = allQuestions.where((q) => q.difficulty == difficulty).toList();
    if (byDiff.isEmpty) return allQuestions.take(count).toList();
    byDiff.shuffle();
    return byDiff.take(count).toList();
  }
  final shuffled = List<Question>.from(filtered)..shuffle();
  return shuffled.take(count > shuffled.length ? shuffled.length : count).toList();
}
